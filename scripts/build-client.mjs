// Assemble lib/client.js — the single browser bundle DSH loads for this package (loader id = package name) —
// from the two Orb client halves in src/client/. Each part is a module-loader factory body that returns
// `module.exports` with `apply` / `inject`; the bundle applies both.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const parts = ["overlay-chat", "settings-orb"];
const factories = parts.map((name) => {
	const body = readFileSync(join(root, "src", "client", `${name}.js`), "utf8");
	const ident = name.replace(/-(.)/g, (_, c) => c.toUpperCase());
	return { ident, code: `\tfunction ${ident}Factory(require) {\n${body}\t}\n` };
});

const out = `/* dsh-orb client half — generated by scripts/build-client.mjs from src/client/*.js; do not edit.
 * - overlay-chat: Orb's Overlay Compact Chat for the floating ball's ?surface=overlay iframe.
 * - settings-orb: Orb's floating-ball Settings page, backed by the plugin's Host routes.
 * Loaded through the client module loader; the loader id MUST equal the package name. */
window.__ModuleLoader__.load({
	id: "dsh-orb",
	factory: (require) => {
${factories.map((f) => f.code).join("")}		const parts = [${factories.map((f) => `${f.ident}Factory(require)`).join(", ")}];
		const module = { exports: {} };
		Object.defineProperty(module.exports, Symbol.toStringTag, { value: "Module" });
		module.exports.inject = [...new Set(parts.flatMap((part) => part.inject ?? []))];
		module.exports.apply = (ctx) => {
			for (const part of parts) part.apply(ctx);
		};
		return module.exports;
	}
});
`;
writeFileSync(join(root, "lib", "client.js"), out);
console.log("lib/client.js", out.length, "bytes");
